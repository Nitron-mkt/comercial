-- Lista A: distribuidoras/atacadistas do Sudeste (SP, RJ, MG, ES) paradas ha 60+ dias, consolidadas por grupo (matriz).
-- Extraida em 27/10/2026. Faturamento = ultimos 24 meses (AD_VW_COM_CLIENTES).
-- Identificacao: nome com DISTRIB/ATACADIST ou tabela de preco de distribuidor/atacado (o Sankhya nao tem campo de segmento).
-- O grupo so entra se NENHUMA filial comprou nos ultimos 60 dias (ex.: filial perdida da Palmares/Amigao fica fora).
-- CODPARCMATRIZ = 0 e tratado como "sem matriz".
WITH CAD AS (
  SELECT C.*, CASE WHEN NVL(C.CODPARCMATRIZ,0)=0 THEN C.CODPARC ELSE C.CODPARCMATRIZ END MZ
    FROM AD_VW_COM_CADCLIENTES C WHERE C.TIPPESSOA='J'),
ALVO AS (
  SELECT DISTINCT MZ FROM CAD
   WHERE UF IN ('SP','RJ','MG','ES')
     AND (UPPER(RAZAOSOCIAL||' '||NOMEPARC) LIKE '%DISTRIB%' OR UPPER(TABELA_PRECO) LIKE '%DISTR%'
          OR UPPER(TABELA_PRECO) LIKE '%ATACAD%' OR UPPER(RAZAOSOCIAL) LIKE '%ATACADIST%')),
B AS (
  SELECT CAD.MZ, CAD.CODPARC, CAD.RAZAOSOCIAL, CAD.NOMEPARC, CAD.CNPJ, CAD.CIDADE, CAD.UF, CAD.VENDEDOR, CAD.GESTOR,
         CAD.KEY_ACCOUNT, CAD.TABELA_PRECO, K.ULTIMA_COMPRA, K.PRIMEIRA_COMPRA, K.NOTAS, K.FATURAMENTO
    FROM CAD JOIN ALVO ON ALVO.MZ=CAD.MZ JOIN AD_VW_COM_CLIENTES K ON K.CODPARC=CAD.CODPARC)
SELECT MZ,
  MAX(RAZAOSOCIAL) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) RAZAO,
  MAX(NOMEPARC) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) FANTASIA,
  MAX(CNPJ) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) CNPJ,
  MAX(CIDADE) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) CIDADE,
  MAX(UF) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) UF,
  MAX(VENDEDOR) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) VEND,
  MAX(GESTOR) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) GEST,
  MAX(KEY_ACCOUNT) KA,
  MAX(TABELA_PRECO) KEEP (DENSE_RANK LAST ORDER BY FATURAMENTO NULLS FIRST) TAB,
  COUNT(*) LOJAS, TO_CHAR(MIN(PRIMEIRA_COMPRA),'YYYY-MM-DD') PRIM, TO_CHAR(MAX(ULTIMA_COMPRA),'YYYY-MM-DD') ULT,
  TRUNC(SYSDATE)-TRUNC(MAX(ULTIMA_COMPRA)) DIAS, SUM(NOTAS) NOTAS, ROUND(SUM(FATURAMENTO)) FAT24M
FROM B GROUP BY MZ
HAVING TRUNC(SYSDATE)-TRUNC(MAX(ULTIMA_COMPRA)) >= 60 AND SUM(FATURAMENTO) >= 1500
ORDER BY FAT24M DESC

