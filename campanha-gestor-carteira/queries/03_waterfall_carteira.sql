-- Achado 3: decomposicao da carteira comum, set/24-ago/25 -> set/25-ago/26.
-- Base 38,96 - churn 10,86 - contracao 10,39 + expansao 5,42 + reativacao 1,89 + novos 7,38 = 32,40
WITH B AS (
  SELECT NVL(P.CODPARCMATRIZ,N.CODPARC) MZ, TRUNC(N.DATA) DT, N.VALOR_NOTA F
    FROM AD_VW_COM_NOTAS N
    JOIN TGFVEN V ON V.CODVEND = N.CODVEND
    JOIN TGFPAR P ON P.CODPARC = N.CODPARC
   WHERE N.DATA >= DATE '2023-09-01' AND N.DATA < DATE '2026-09-01'
     AND V.TIPVEND='R' AND V.ATIVO='S' AND N.CODVEND <> 137
     AND P.AD_CODGRUKEY IS NULL AND N.CODTIPOPER NOT IN (3226,3244)
),
A1  AS (SELECT MZ, SUM(F) FAT FROM B WHERE DT >= DATE '2024-09-01' AND DT < DATE '2025-09-01' GROUP BY MZ),
A2  AS (SELECT MZ, SUM(F) FAT FROM B WHERE DT >= DATE '2025-09-01' GROUP BY MZ),
ANT AS (SELECT DISTINCT MZ FROM B WHERE DT < DATE '2024-09-01')
SELECT ROUND(SUM(CASE WHEN A1.MZ IS NOT NULL THEN A1.FAT ELSE 0 END)/1000000,2) BASE_ANO1_MI,
       ROUND(SUM(CASE WHEN A1.MZ IS NOT NULL AND A2.MZ IS NULL THEN -A1.FAT ELSE 0 END)/1000000,2) CHURN_MI,
       ROUND(SUM(CASE WHEN A1.MZ IS NOT NULL AND A2.MZ IS NOT NULL AND A2.FAT <  A1.FAT THEN A2.FAT-A1.FAT ELSE 0 END)/1000000,2) CONTRACAO_MI,
       ROUND(SUM(CASE WHEN A1.MZ IS NOT NULL AND A2.MZ IS NOT NULL AND A2.FAT >= A1.FAT THEN A2.FAT-A1.FAT ELSE 0 END)/1000000,2) EXPANSAO_MI,
       ROUND(SUM(CASE WHEN A1.MZ IS NULL AND A2.MZ IS NOT NULL AND ANT.MZ IS NOT NULL THEN A2.FAT ELSE 0 END)/1000000,2) REATIVADO_MI,
       ROUND(SUM(CASE WHEN A1.MZ IS NULL AND A2.MZ IS NOT NULL AND ANT.MZ IS NULL     THEN A2.FAT ELSE 0 END)/1000000,2) NOVO_MI,
       SUM(CASE WHEN A1.MZ IS NOT NULL AND A2.MZ IS NULL THEN 1 ELSE 0 END) QTD_CHURN,
       SUM(CASE WHEN A1.MZ IS NULL AND A2.MZ IS NOT NULL AND ANT.MZ IS NOT NULL THEN 1 ELSE 0 END) QTD_REATIVADO,
       SUM(CASE WHEN A1.MZ IS NULL AND A2.MZ IS NOT NULL AND ANT.MZ IS NULL     THEN 1 ELSE 0 END) QTD_NOVO
  FROM A1
  FULL OUTER JOIN A2 ON A2.MZ = A1.MZ
  LEFT JOIN ANT ON ANT.MZ = NVL(A1.MZ, A2.MZ);

-- Positivou e caiu: 98 dos 583 positivados de mai-ago/26 caem >30% contra mai-ago/25 (-R$ 1,02 mi)
WITH B AS (
  SELECT NVL(P.CODPARCMATRIZ,N.CODPARC) MZ, TRUNC(N.DATA) DT, N.VALOR_NOTA F
    FROM AD_VW_COM_NOTAS N
    JOIN TGFVEN V ON V.CODVEND = N.CODVEND
    JOIN TGFPAR P ON P.CODPARC = N.CODPARC
   WHERE N.DATA >= DATE '2025-01-01' AND N.DATA < DATE '2026-09-01'
     AND V.TIPVEND='R' AND V.ATIVO='S' AND N.CODVEND <> 137
     AND P.AD_CODGRUKEY IS NULL AND N.CODTIPOPER NOT IN (3226,3244)
),
Q_ANT AS (SELECT MZ, SUM(F) FAT FROM B WHERE DT >= DATE '2025-05-01' AND DT < DATE '2025-09-01' GROUP BY MZ),
Q_ATU AS (SELECT B.MZ, SUM(B.F) FAT, MAX(CASE WHEN X.V >= 3500 THEN 1 ELSE 0 END) POSIT
            FROM B
            JOIN (SELECT MZ MZ2, DT DT2, SUM(F) V FROM B WHERE DT >= DATE '2026-05-01' GROUP BY MZ, DT) X
              ON X.MZ2 = B.MZ AND X.DT2 = B.DT
           WHERE B.DT >= DATE '2026-05-01' GROUP BY B.MZ)
SELECT COUNT(*) POSITIVADOS,
       SUM(CASE WHEN Q_ANT.FAT IS NOT NULL AND Q_ATU.FAT < Q_ANT.FAT*0.7 THEN 1 ELSE 0 END) POSIT_MAS_CAIU_30,
       ROUND(SUM(CASE WHEN Q_ANT.FAT IS NOT NULL AND Q_ATU.FAT < Q_ANT.FAT*0.7
                      THEN Q_ATU.FAT - Q_ANT.FAT END)/1000000,2) PERDA_MI
  FROM Q_ATU LEFT JOIN Q_ANT ON Q_ANT.MZ = Q_ATU.MZ
 WHERE Q_ATU.POSIT = 1;
