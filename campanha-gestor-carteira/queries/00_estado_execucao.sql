-- (a) nenhuma tabela AD_CAMP_* existe no schema
SELECT OBJECT_NAME, OBJECT_TYPE, TO_CHAR(CREATED,'YYYY-MM-DD') CRIADO
  FROM ALL_OBJECTS
 WHERE OBJECT_NAME LIKE 'AD_CAMP%'
 ORDER BY OBJECT_NAME;

-- (b) TGFTOP.AD_CONTAPOSIT nao existe; AD_CLUBENITRON e AD_CODGRUKEY existem
SELECT
  (SELECT COUNT(*) FROM ALL_TAB_COLUMNS WHERE TABLE_NAME='TGFTOP' AND COLUMN_NAME='AD_CONTAPOSIT') COL_CONTAPOSIT,
  (SELECT COUNT(*) FROM ALL_TAB_COLUMNS WHERE TABLE_NAME='TGFPAR' AND COLUMN_NAME='AD_CLUBENITRON') COL_CLUBE,
  (SELECT COUNT(*) FROM ALL_TAB_COLUMNS WHERE TABLE_NAME='TGFPAR' AND COLUMN_NAME='AD_CODGRUKEY')  COL_KEY,
  (SELECT TO_CHAR(MAX(DATA),'YYYY-MM-DD') FROM AD_VW_COM_NOTAS) ULT_MOVIMENTO
FROM DUAL;

-- (c) metas mensais: set-dez/2026 chapadas em R$ 12,51 mi; fev-abr/2027 zeradas
SELECT TO_CHAR(M.DTREF,'YYYY-MM') REF,
       COUNT(DISTINCT M.CODVEND) QTD_VEND,
       ROUND(SUM(M.PREVREC)/1000000,2) META_MI
  FROM TGMMET M
 WHERE M.DTREF >= DATE '2026-01-01' AND M.DTREF < DATE '2027-05-01'
 GROUP BY TO_CHAR(M.DTREF,'YYYY-MM')
 ORDER BY 1;

-- (d) higiene do cadastro na carteira: CODPARC=0 e clientes inativos/bloqueados
WITH B AS (
  SELECT N.CODVEND, N.CODPARC, NVL(P.CODPARCMATRIZ,N.CODPARC) MZ, N.VALOR_NOTA,
         NVL(P.ATIVO,'S') PATIVO, NVL(P.BLOQUEAR,'N') PBLOQ, NVL(P.AD_CLUBENITRON,'N') CLUBE
    FROM AD_VW_COM_NOTAS N
    JOIN TGFVEN V ON V.CODVEND = N.CODVEND
    JOIN TGFPAR P ON P.CODPARC = N.CODPARC
   WHERE N.DATA >= DATE '2025-09-01' AND N.DATA < DATE '2026-09-01'
     AND V.TIPVEND='R' AND V.ATIVO='S' AND N.CODVEND <> 137
     AND P.AD_CODGRUKEY IS NULL
     AND N.CODTIPOPER NOT IN (3226,3244)   -- substituir por AD_CONTAPOSIT quando existir
)
SELECT COUNT(DISTINCT MZ) CARTEIRA_TOTAL,
       COUNT(DISTINCT CASE WHEN PATIVO='N' THEN MZ END) CLI_CADASTRO_INATIVO,
       COUNT(DISTINCT CASE WHEN PBLOQ='S'  THEN MZ END) CLI_BLOQUEADO,
       ROUND(SUM(CASE WHEN PATIVO='N' OR PBLOQ='S' THEN VALOR_NOTA END)/1000000,2) FAT_EXCLUIDO_MI,
       COUNT(DISTINCT CASE WHEN CLUBE='S' THEN MZ END) CLI_CLUBE,
       ROUND(SUM(CASE WHEN CODPARC=0 THEN VALOR_NOTA END)/1000,1) FAT_PARC0_K
  FROM B;
