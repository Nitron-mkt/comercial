-- Achado 5: efeito do contrato Clube, controlando pela frequencia de partida.
-- Coorte de set/24-ago/25 seguida em set/25-ago/26. Mesmo ponto de partida em cada linha.
-- Retencao 1 compra/ano: 36,0% sem Clube contra 96,0% com Clube.
WITH B AS (
  SELECT NVL(P.CODPARCMATRIZ,N.CODPARC) MZ, TRUNC(N.DATA) DT, N.VALOR_NOTA F,
         NVL(P.AD_CLUBENITRON,'N') CLUBE
    FROM AD_VW_COM_NOTAS N
    JOIN TGFVEN V ON V.CODVEND = N.CODVEND
    JOIN TGFPAR P ON P.CODPARC = N.CODPARC
   WHERE N.DATA >= DATE '2024-09-01' AND N.DATA < DATE '2026-09-01'
     AND V.TIPVEND='R' AND V.ATIVO='S' AND N.CODVEND <> 137
     AND P.AD_CODGRUKEY IS NULL AND N.CODTIPOPER NOT IN (3226,3244)
),
G AS (
  SELECT MZ, MAX(CLUBE) CLUBE,
         COUNT(DISTINCT CASE WHEN DT <  DATE '2025-09-01' THEN DT END) NC1,
         COUNT(DISTINCT CASE WHEN DT >= DATE '2025-09-01' THEN DT END) NC2,
         SUM(CASE WHEN DT <  DATE '2025-09-01' THEN F ELSE 0 END) F1,
         SUM(CASE WHEN DT >= DATE '2025-09-01' THEN F ELSE 0 END) F2
    FROM B GROUP BY MZ
)
SELECT CASE WHEN NC1 = 1 THEN 'A. 1 compra'
            WHEN NC1 <= 3  THEN 'B. 2-3'
            WHEN NC1 <= 11 THEN 'C. 4-11'
            ELSE 'D. 12+' END FAIXA_ANO_ANTERIOR,
       CLUBE, COUNT(*) CLIENTES,
       ROUND(AVG(NC1),2) COMPRAS_ANO_ANT, ROUND(AVG(NC2),2) COMPRAS_ANO_ATU,
       ROUND(AVG(CASE WHEN NC2 > 0 THEN 1 ELSE 0 END)*100,1) RETENCAO_PCT,
       ROUND(SUM(F1)/1000000,2) FAT_ANT_MI, ROUND(SUM(F2)/1000000,2) FAT_ATU_MI,
       ROUND((SUM(F2)/NULLIF(SUM(F1),0)-1)*100,1) VAR_PCT
  FROM G
 WHERE NC1 > 0
 GROUP BY CASE WHEN NC1 = 1 THEN 'A. 1 compra'
               WHEN NC1 <= 3  THEN 'B. 2-3'
               WHEN NC1 <= 11 THEN 'C. 4-11'
               ELSE 'D. 12+' END, CLUBE
 ORDER BY 1, 2;
