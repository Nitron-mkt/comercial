-- Achado 1: a regua dupla (45% positivacao + 90% meta) aprova 1 dos 27 reps
-- com carteira >= 20 clientes. Quadrimestre-espelho: mai-ago/2026.
-- Proxy de meta: realizado set-dez/2025 sobre a meta de set-dez/2026.
WITH BASE AS (
  SELECT N.CODVEND, NVL(P.CODPARCMATRIZ,N.CODPARC) MZ, TRUNC(N.DATA) DT, N.VALOR_NOTA
    FROM AD_VW_COM_NOTAS N
    JOIN TGFVEN V ON V.CODVEND = N.CODVEND
    JOIN TGFPAR P ON P.CODPARC = N.CODPARC
   WHERE N.DATA >= DATE '2023-09-01' AND N.DATA < DATE '2026-09-01'
     AND V.TIPVEND='R' AND V.ATIVO='S' AND N.CODVEND <> 137
     AND P.AD_CODGRUKEY IS NULL AND N.CODTIPOPER NOT IN (3226,3244)
),
CART AS (SELECT DISTINCT CODVEND, MZ FROM BASE WHERE DT >= DATE '2025-09-01'),
INAT AS (SELECT CODVEND, MZ FROM BASE WHERE DT <  DATE '2025-09-01' GROUP BY CODVEND, MZ),
-- positivacao por evento-dia; a consolidacao de 7 dias (R07) esta na especificacao tecnica
EVT  AS (SELECT CODVEND, MZ, DT, SUM(VALOR_NOTA) V FROM BASE WHERE DT >= DATE '2026-05-01' GROUP BY CODVEND, MZ, DT),
POS  AS (SELECT CODVEND, COUNT(DISTINCT CASE WHEN V >= 3500 THEN MZ END) P35 FROM EVT GROUP BY CODVEND),
C    AS (SELECT CODVEND, COUNT(*) QC FROM CART GROUP BY CODVEND),
I    AS (SELECT I.CODVEND, COUNT(*) QI FROM INAT I
          WHERE NOT EXISTS (SELECT 1 FROM CART C2 WHERE C2.CODVEND=I.CODVEND AND C2.MZ=I.MZ)
          GROUP BY I.CODVEND),
MET  AS (SELECT CODVEND, SUM(PREVREC) META FROM TGMMET
          WHERE DTREF >= DATE '2026-09-01' AND DTREF < DATE '2027-01-01' GROUP BY CODVEND),
FAT  AS (SELECT CODVEND, SUM(VALOR_NOTA) F FROM AD_VW_COM_NOTAS
          WHERE DATA >= DATE '2025-09-01' AND DATA < DATE '2026-01-01' GROUP BY CODVEND)
SELECT V.APELIDO REP, C.QC CARTEIRA, NVL(I.QI,0) INATIVOS, NVL(POS.P35,0) POSITIVADOS,
       ROUND(NVL(POS.P35,0)/C.QC*100,1) PCT_POSIT,
       CEIL(C.QC*0.45) ALVO_45,
       GREATEST(0, CEIL(C.QC*0.45) - NVL(POS.P35,0)) FALTAM,
       ROUND(NVL(MET.META,0)/1000,0) META_SETDEZ26_K,
       ROUND(NVL(FAT.F,0)/1000,0)    FAT_SETDEZ25_K,
       ROUND(NVL(FAT.F,0)/NULLIF(MET.META,0)*100,1) PCT_META_PROXY
  FROM C
  JOIN TGFVEN V ON V.CODVEND = C.CODVEND
  LEFT JOIN POS ON POS.CODVEND = C.CODVEND
  LEFT JOIN I   ON I.CODVEND   = C.CODVEND
  LEFT JOIN MET ON MET.CODVEND = C.CODVEND
  LEFT JOIN FAT ON FAT.CODVEND = C.CODVEND
 WHERE C.QC >= 20
 ORDER BY C.QC DESC;
