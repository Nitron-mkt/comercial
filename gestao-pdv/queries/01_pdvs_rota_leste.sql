-- Selecao de PDVs da rota Leste / Alto Tiete (24/11/2026)
-- Reps: 17 MILTON, 19 CARLINHOS, 93 EDSON GRAVINEZ, 135 DIEGO (Diego: 1 cliente, sem venda na rota)
-- Empresas de venda da view (1,2,3,4,14). Loja = CODPARC (CNPJ). Valores em R$ mil, brutos (VALOR_NOTA).
-- Resultado: 268 lojas com compra em 24 meses -> app/pdvs.json via app/classificar_pdvs.py
WITH X_CLI AS (
 SELECT CODPARC, NOMEPARC, CNPJ, CODPARCMATRIZ, MATRIZ, KEY_ACCOUNT, CODVEND, VENDEDOR, CIDADE
 FROM AD_VW_COM_CADCLIENTES
 WHERE CODVEND IN (17,19,93,135) AND TIPPESSOA='J' AND ATIVO='S' AND NVL(BLOQUEAR,'N')='N'
   AND UPPER(CIDADE) IN ('SAO PAULO','GUARULHOS','MOGI DAS CRUZES','ITAQUAQUECETUBA','SUZANO','ARUJA')
), X_VEN AS (
 SELECT CODPARC,
   SUM(CASE WHEN DATA >= DATE '2025-11-01' AND DATA < DATE '2026-11-01' THEN VALOR_NOTA END) F12,
   SUM(CASE WHEN DATA >= DATE '2024-11-01' AND DATA < DATE '2025-11-01' THEN VALOR_NOTA END) F12A,
   SUM(CASE WHEN DATA >= DATE '2026-05-01' AND DATA < DATE '2026-11-01' THEN VALOR_NOTA END) F6,
   COUNT(DISTINCT CASE WHEN DATA >= DATE '2025-11-01' AND DATA < DATE '2026-11-01' THEN ANO_MES END) MESES,
   MAX(DATA) ULT
 FROM AD_VW_COM_NOTAS WHERE DATA >= DATE '2024-11-01' AND CODPARC IN (SELECT CODPARC FROM X_CLI)
 GROUP BY CODPARC),
X_REDE AS (SELECT NVL(CODPARCMATRIZ,CODPARC) MZ, COUNT(*) LOJAS FROM AD_VW_COM_CADCLIENTES WHERE ATIVO='S' AND TIPPESSOA='J' GROUP BY NVL(CODPARCMATRIZ,CODPARC))
SELECT C.CODPARC COD, SUBSTR(C.NOMEPARC,1,32) LOJA, C.CNPJ, SUBSTR(C.MATRIZ,1,24) MATRIZ, R.LOJAS, SUBSTR(C.KEY_ACCOUNT,1,18) KA, C.VENDEDOR REP, C.CIDADE,
 ROUND(NVL(V.F12,0)/1000,1) F12, ROUND(NVL(V.F12A,0)/1000,1) F12A, ROUND(NVL(V.F6,0)/1000,1) F6, NVL(V.MESES,0) M, TO_CHAR(V.ULT,'YYYY-MM-DD') ULT
FROM X_CLI C LEFT JOIN X_VEN V ON V.CODPARC=C.CODPARC LEFT JOIN X_REDE R ON R.MZ = NVL(C.CODPARCMATRIZ,C.CODPARC)
WHERE NVL(V.F12,0)+NVL(V.F12A,0) > 0
ORDER BY GREATEST(NVL(V.F12,0),NVL(V.F12A,0)) DESC
